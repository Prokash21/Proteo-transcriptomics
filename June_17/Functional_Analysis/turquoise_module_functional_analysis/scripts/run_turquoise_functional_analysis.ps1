param(
  [string]$InputCsv = "..\inputs\turquoise_module_genes.csv",
  [string]$OutputRoot = "..",
  [string]$Organism = "hsapiens",
  [double]$PValueCutoff = 0.05
)

$ErrorActionPreference = "Stop"

function Resolve-FromScriptDir([string]$PathValue) {
  if ([System.IO.Path]::IsPathRooted($PathValue)) { return $PathValue }
  return Join-Path $PSScriptRoot $PathValue
}

function Split-GeneField([string]$Value) {
  @($Value -split ";" | ForEach-Object { $_.Trim() } | Where-Object { $_ })
}

function ConvertTo-NegLog10([double]$PValue) {
  if ($PValue -le 0) { return 300 }
  return -[Math]::Log10($PValue)
}

function Limit-Text([string]$Text, [int]$MaxLength) {
  if ($Text.Length -le $MaxLength) { return $Text }
  return $Text.Substring(0, $MaxLength - 1) + "…"
}

function New-PdfFromPng([string]$PngPath, [string]$PdfPath) {
  Add-Type -AssemblyName System.Drawing
  $image = [System.Drawing.Image]::FromFile($PngPath)
  try {
    $tempJpeg = [System.IO.Path]::ChangeExtension([System.IO.Path]::GetTempFileName(), ".jpg")
    $white = [System.Drawing.Bitmap]::new($image.Width, $image.Height, [System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $graphics = [System.Drawing.Graphics]::FromImage($white)
    try {
      $graphics.Clear([System.Drawing.Color]::White)
      $graphics.DrawImage($image, 0, 0, $image.Width, $image.Height)
      $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq "image/jpeg" } | Select-Object -First 1
      $params = [System.Drawing.Imaging.EncoderParameters]::new(1)
      $params.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, 95L)
      $white.Save($tempJpeg, $codec, $params)
    } finally {
      if ($graphics) { $graphics.Dispose() }
      if ($white) { $white.Dispose() }
    }

    $jpegBytes = [System.IO.File]::ReadAllBytes($tempJpeg)
    $pageWidth = [Math]::Round($image.Width * 0.75, 2)
    $pageHeight = [Math]::Round($image.Height * 0.75, 2)
    $content = "q`n$pageWidth 0 0 $pageHeight 0 0 cm`n/Im1 Do`nQ`n"
    $contentBytes = [System.Text.Encoding]::ASCII.GetBytes($content)

    $objects = @(
      [pscustomobject]@{ Kind = "binary"; Header = "<< /Type /XObject /Subtype /Image /Width $($image.Width) /Height $($image.Height) /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length $($jpegBytes.Length) >>`nstream`n"; Bytes = $jpegBytes; Footer = "`nendstream" },
      [pscustomobject]@{ Kind = "text"; Text = "<< /Length $($contentBytes.Length) >>`nstream`n$content`nendstream" },
      [pscustomobject]@{ Kind = "text"; Text = "<< /Type /Page /Parent 4 0 R /MediaBox [0 0 $pageWidth $pageHeight] /Resources << /XObject << /Im1 1 0 R >> >> /Contents 2 0 R >>" },
      [pscustomobject]@{ Kind = "text"; Text = "<< /Type /Pages /Kids [3 0 R] /Count 1 >>" },
      [pscustomobject]@{ Kind = "text"; Text = "<< /Type /Catalog /Pages 4 0 R >>" }
    )

    $stream = [System.IO.MemoryStream]::new()
    $ascii = [System.Text.Encoding]::ASCII
    function Write-Text([string]$Text) {
      $bytes = $ascii.GetBytes($Text)
      $script:pdfStream.Write($bytes, 0, $bytes.Length)
    }
    function Write-Bytes([byte[]]$Bytes) {
      $script:pdfStream.Write($Bytes, 0, $Bytes.Length)
    }

    $script:pdfStream = $stream
    Write-Text "%PDF-1.4`n%Generated by turquoise module functional analysis`n"
    $offsets = @(0)
    for ($i = 0; $i -lt $objects.Count; $i++) {
      $offsets += $stream.Position
      Write-Text "$($i + 1) 0 obj`n"
      if ($objects[$i].Kind -eq "binary") {
        Write-Text $objects[$i].Header
        Write-Bytes $objects[$i].Bytes
        Write-Text $objects[$i].Footer
      } else {
        Write-Text $objects[$i].Text
      }
      Write-Text "`nendobj`n"
    }
    $xrefOffset = $stream.Position
    Write-Text "xref`n0 6`n0000000000 65535 f `n"
    for ($i = 1; $i -lt $offsets.Count; $i++) {
      Write-Text ("{0:D10} 00000 n `n" -f [int]$offsets[$i])
    }
    Write-Text "trailer`n<< /Size 6 /Root 5 0 R >>`nstartxref`n$xrefOffset`n%%EOF`n"
    [System.IO.File]::WriteAllBytes($PdfPath, $stream.ToArray())
    $stream.Dispose()
    Remove-Variable -Name pdfStream -Scope Script -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $tempJpeg -Force -ErrorAction SilentlyContinue
  } finally {
    if ($image) { $image.Dispose() }
  }
}

function New-BarPlot($Rows, [string]$PngPath, [string]$Title, [string]$ValueColumn, [string]$LabelColumn, [string]$XAxisLabel) {
  Add-Type -AssemblyName System.Drawing
  $plotRows = @($Rows)
  if ($plotRows.Count -eq 0) { return }
  $width = 1800
  $height = [Math]::Max(900, 190 + ($plotRows.Count * 34))
  $left = 560
  $right = 110
  $top = 115
  $bottom = 95
  $plotWidth = $width - $left - $right
  $plotHeight = $height - $top - $bottom
  $maxValue = [double](($plotRows | ForEach-Object { [double]$_.$ValueColumn } | Measure-Object -Maximum).Maximum)
  if ($maxValue -le 0) { $maxValue = 1 }

  $bitmap = [System.Drawing.Bitmap]::new($width, $height)
  $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
  try {
    $graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $graphics.Clear([System.Drawing.Color]::White)
    $titleFont = [System.Drawing.Font]::new("Arial", 26, [System.Drawing.FontStyle]::Bold)
    $labelFont = [System.Drawing.Font]::new("Arial", 14)
    $axisFont = [System.Drawing.Font]::new("Arial", 13)
    $smallFont = [System.Drawing.Font]::new("Arial", 11)
    $black = [System.Drawing.Brushes]::Black
    $gray = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 75, 85, 99))
    $blue = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 76, 120, 168))
    $axisPen = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(255, 156, 163, 175), 2)
    $graphics.DrawString($Title, $titleFont, $black, 40, 35)
    $graphics.DrawLine($axisPen, $left, $top, $left, $top + $plotHeight)
    $graphics.DrawLine($axisPen, $left, $top + $plotHeight, $left + $plotWidth, $top + $plotHeight)

    $barGap = 10
    $barHeight = [Math]::Max(16, [Math]::Min(28, ($plotHeight / $plotRows.Count) - $barGap))
    for ($i = 0; $i -lt $plotRows.Count; $i++) {
      $row = $plotRows[$i]
      $value = [double]$row.$ValueColumn
      $barWidth = [Math]::Max(2, ($value / $maxValue) * $plotWidth)
      $y = $top + ($i * ($plotHeight / $plotRows.Count)) + 4
      $graphics.DrawString((Limit-Text ([string]$row.$LabelColumn) 66), $labelFont, $black, 30, $y - 2)
      $graphics.FillRectangle($blue, $left, $y, $barWidth, $barHeight)
      $graphics.DrawString(("{0:N2}" -f $value), $smallFont, $gray, $left + $barWidth + 8, $y + 1)
    }
    $graphics.DrawString($XAxisLabel, $axisFont, $gray, $left + 360, $height - 55)
    $bitmap.Save($PngPath, [System.Drawing.Imaging.ImageFormat]::Png)
  } finally {
    if ($graphics) { $graphics.Dispose() }
    if ($bitmap) { $bitmap.Dispose() }
  }
}

function New-SummaryPlot($Rows, [string]$PngPath) {
  Add-Type -AssemblyName System.Drawing
  $plotRows = @($Rows | Sort-Object significant_terms -Descending)
  if ($plotRows.Count -eq 0) { return }
  $width = 1400
  $height = 850
  $left = 130
  $right = 60
  $top = 130
  $bottom = 130
  $plotWidth = $width - $left - $right
  $plotHeight = $height - $top - $bottom
  $maxValue = [double](($plotRows.significant_terms | Measure-Object -Maximum).Maximum)
  if ($maxValue -le 0) { $maxValue = 1 }
  $barWidth = [Math]::Min(120, ($plotWidth / $plotRows.Count) * 0.65)

  $bitmap = [System.Drawing.Bitmap]::new($width, $height)
  $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
  try {
    $graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $graphics.Clear([System.Drawing.Color]::White)
    $titleFont = [System.Drawing.Font]::new("Arial", 27, [System.Drawing.FontStyle]::Bold)
    $labelFont = [System.Drawing.Font]::new("Arial", 15)
    $smallFont = [System.Drawing.Font]::new("Arial", 12)
    $black = [System.Drawing.Brushes]::Black
    $gray = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 75, 85, 99))
    $orange = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 245, 133, 24))
    $axisPen = [System.Drawing.Pen]::new([System.Drawing.Color]::FromArgb(255, 156, 163, 175), 2)
    $graphics.DrawString("Significant enriched terms by database", $titleFont, $black, 40, 40)
    $graphics.DrawLine($axisPen, $left, $top, $left, $top + $plotHeight)
    $graphics.DrawLine($axisPen, $left, $top + $plotHeight, $left + $plotWidth, $top + $plotHeight)
    for ($i = 0; $i -lt $plotRows.Count; $i++) {
      $row = $plotRows[$i]
      $value = [double]$row.significant_terms
      $xCenter = $left + (($i + 0.5) * ($plotWidth / $plotRows.Count))
      $barHeight = ($value / $maxValue) * $plotHeight
      $x = $xCenter - ($barWidth / 2)
      $y = $top + $plotHeight - $barHeight
      $graphics.FillRectangle($orange, $x, $y, $barWidth, $barHeight)
      $graphics.DrawString([string]$value, $smallFont, $gray, $x + 18, $y - 25)
      $graphics.TranslateTransform($xCenter - 8, $top + $plotHeight + 22)
      $graphics.RotateTransform(45)
      $graphics.DrawString([string]$row.source, $labelFont, $black, 0, 0)
      $graphics.ResetTransform()
    }
    $graphics.DrawString("Number of significant terms (g:SCS adjusted p < 0.05)", $labelFont, $gray, 420, $height - 45)
    $bitmap.Save($PngPath, [System.Drawing.Imaging.ImageFormat]::Png)
  } finally {
    if ($graphics) { $graphics.Dispose() }
    if ($bitmap) { $bitmap.Dispose() }
  }
}

$inputPath = Resolve-FromScriptDir $InputCsv
$outputRootPath = Resolve-FromScriptDir $OutputRoot
$rawDir = Join-Path $outputRootPath "results\raw"
$processedDir = Join-Path $outputRootPath "results\processed"
$pngDir = Join-Path $outputRootPath "figures\png"
$pdfDir = Join-Path $outputRootPath "figures\pdf"
$reportDir = Join-Path $outputRootPath "report"
New-Item -ItemType Directory -Force -Path $rawDir, $processedDir, $pngDir, $pdfDir, $reportDir | Out-Null

$inputRows = Import-Csv $inputPath
$genes = @($inputRows | ForEach-Object { Split-GeneField ([string]$_.gene) } | Sort-Object -Unique)
if ($genes.Count -eq 0) { throw "No genes found in $inputPath" }

$genes | ForEach-Object { [pscustomobject]@{ gene = $_ } } | Export-Csv -Path (Join-Path $processedDir "turquoise_module_clean_genes.csv") -NoTypeInformation
$genes | Set-Content -Path (Join-Path $processedDir "turquoise_module_clean_genes.txt") -Encoding UTF8

$request = @{
  organism = $Organism
  query = $genes
  sources = @("GO:BP", "GO:MF", "GO:CC", "KEGG", "REAC", "WP")
  user_threshold = $PValueCutoff
  all_results = $false
  ordered = $false
  no_evidences = $true
  domain_scope = "annotated"
  significance_threshold_method = "g_SCS"
}
$requestJson = $request | ConvertTo-Json -Depth 10
Set-Content -Path (Join-Path $rawDir "gprofiler_request.json") -Value $requestJson -Encoding UTF8

$response = Invoke-RestMethod -Method Post -Uri "https://biit.cs.ut.ee/gprofiler/api/gost/profile/" -Body $requestJson -ContentType "application/json"
$response | ConvertTo-Json -Depth 100 | Set-Content -Path (Join-Path $rawDir "gprofiler_response.json") -Encoding UTF8

$results = @($response.result | ForEach-Object {
  $intersection = @()
  if ($_.intersections) { $intersection = @($_.intersections) }
  elseif ($_.intersection) { $intersection = @($_.intersection) }
  [pscustomobject]@{
    source = $_.source
    term_id = $_.native
    term_name = $_.name
    adjusted_p_value = [double]$_.p_value
    negative_log10_p = ConvertTo-NegLog10 ([double]$_.p_value)
    significant = [bool]$_.significant
    term_size = $_.term_size
    query_size = $_.query_size
    overlap_size = $_.intersection_size
    effective_domain_size = $_.effective_domain_size
    precision = $_.precision
    recall = $_.recall
    intersection_genes = ($intersection -join ";")
  }
})

$results | Sort-Object adjusted_p_value | Export-Csv -Path (Join-Path $processedDir "gprofiler_enrichment_all_results.csv") -NoTypeInformation
$significant = @($results | Where-Object { $_.significant -eq $true -and $_.adjusted_p_value -le $PValueCutoff } | Sort-Object adjusted_p_value)
$significant | Export-Csv -Path (Join-Path $processedDir "gprofiler_enrichment_significant.csv") -NoTypeInformation

$summary = @($results | Group-Object source | ForEach-Object {
  $sourceRows = @($_.Group)
  [pscustomobject]@{
    source = $_.Name
    returned_terms = $sourceRows.Count
    significant_terms = @($sourceRows | Where-Object { $_.significant -eq $true -and $_.adjusted_p_value -le $PValueCutoff }).Count
    top_term = ($sourceRows | Sort-Object adjusted_p_value | Select-Object -First 1).term_name
    top_adjusted_p_value = ($sourceRows | Sort-Object adjusted_p_value | Select-Object -First 1).adjusted_p_value
  }
})
$summary | Sort-Object significant_terms -Descending | Export-Csv -Path (Join-Path $processedDir "enrichment_source_summary.csv") -NoTypeInformation

$topOverall = @($significant | Sort-Object adjusted_p_value | Select-Object -First 25 | ForEach-Object {
  $_ | Add-Member -NotePropertyName plot_label -NotePropertyValue ("[$($_.source)] " + $_.term_name) -Force
  $_
})
$topPerSource = @($significant | Group-Object source | ForEach-Object {
  $_.Group | Sort-Object adjusted_p_value | Select-Object -First 6
} | ForEach-Object {
  $_ | Add-Member -NotePropertyName plot_label -NotePropertyValue ("[$($_.source)] " + $_.term_name) -Force
  $_
})
$topOverall | Export-Csv -Path (Join-Path $processedDir "top25_enriched_terms_for_plot.csv") -NoTypeInformation
$topPerSource | Export-Csv -Path (Join-Path $processedDir "top_terms_per_database_for_plot.csv") -NoTypeInformation

$overallPng = Join-Path $pngDir "top25_enriched_terms_barplot.png"
$perSourcePng = Join-Path $pngDir "top_terms_per_database_barplot.png"
$summaryPng = Join-Path $pngDir "significant_terms_by_database.png"
New-BarPlot -Rows $topOverall -PngPath $overallPng -Title "Turquoise module: top enriched functional terms" -ValueColumn "negative_log10_p" -LabelColumn "plot_label" -XAxisLabel "-log10(adjusted p-value)"
New-BarPlot -Rows $topPerSource -PngPath $perSourcePng -Title "Turquoise module: top enriched terms per database" -ValueColumn "negative_log10_p" -LabelColumn "plot_label" -XAxisLabel "-log10(adjusted p-value)"
New-SummaryPlot -Rows $summary -PngPath $summaryPng

foreach ($png in @($overallPng, $perSourcePng, $summaryPng)) {
  if (Test-Path $png) {
    New-PdfFromPng -PngPath $png -PdfPath (Join-Path $pdfDir ([System.IO.Path]::GetFileNameWithoutExtension($png) + ".pdf"))
  }
}

$topTermsMarkdown = @($topOverall | Select-Object -First 12 | ForEach-Object {
  "| $($_.source) | $($_.term_name -replace '\|','/') | $($_.overlap_size) | $([string]::Format('{0:E2}', [double]$_.adjusted_p_value)) |"
})
$summaryMarkdown = @($summary | Sort-Object significant_terms -Descending | ForEach-Object {
  "| $($_.source) | $($_.returned_terms) | $($_.significant_terms) | $($_.top_term -replace '\|','/') | $([string]::Format('{0:E2}', [double]$_.top_adjusted_p_value)) |"
})

$dominantSources = @($summary | Sort-Object significant_terms -Descending | Select-Object -First 3 | ForEach-Object { "$($_.source) ($($_.significant_terms) terms)" }) -join ", "
$topThemes = @($topOverall | Select-Object -First 5 | ForEach-Object { $_.term_name }) -join "; "

$report = @"
# Turquoise module functional enrichment analysis

## Input and method

- Input file: `inputs/turquoise_module_genes.csv`
- Cleaned genes: $($genes.Count)
- Organism: $Organism
- Method: over-representation analysis using g:Profiler g:OST
- Databases queried: GO Biological Process, GO Molecular Function, GO Cellular Component, KEGG, Reactome, WikiPathways
- Multiple-testing method: g:SCS adjusted p-value
- Significance cutoff: adjusted p-value < $PValueCutoff

## High-level interpretation

The turquoise module shows enrichment across $dominantSources. The strongest terms among the top results are: $topThemes.

Interpretation should focus on recurrent biological themes across databases rather than a single isolated term. Terms that appear consistently in GO, Reactome, KEGG, or WikiPathways are stronger evidence for module-level biology.

## Significant term counts by source

| Source | Returned enriched terms | Significant terms | Top term | Top adjusted p-value |
| --- | ---: | ---: | --- | ---: |
$($summaryMarkdown -join "`n")

## Top enriched terms

| Source | Term | Overlap genes | Adjusted p-value |
| --- | --- | ---: | ---: |
$($topTermsMarkdown -join "`n")

## Generated figures

- figures/png/top25_enriched_terms_barplot.png
- figures/png/top_terms_per_database_barplot.png
- figures/png/significant_terms_by_database.png
- PDF versions are in figures/pdf/.

## Result tables

- results/processed/gprofiler_enrichment_all_results.csv
- results/processed/gprofiler_enrichment_significant.csv
- results/processed/enrichment_source_summary.csv
- results/processed/turquoise_module_clean_genes.csv

## Reproducibility

The runnable PowerShell workflow is scripts/run_turquoise_functional_analysis.ps1. R and Python equivalents are saved in scripts/, with package manifests in requirements/.
"@
Set-Content -Path (Join-Path $reportDir "turquoise_module_functional_analysis_report.md") -Value $report -Encoding UTF8

Write-Output "Cleaned genes: $($genes.Count)"
Write-Output "Total enriched terms returned: $($results.Count)"
Write-Output "Significant enriched terms: $($significant.Count)"
Write-Output "Results saved to: $outputRootPath"
